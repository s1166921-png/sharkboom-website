/** Compress geometry and animation without simplifying the character or removing its rig. */
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {dedup,weld,meshopt,prune} from '@gltf-transform/functions';
import {MeshoptEncoder,MeshoptDecoder} from 'meshoptimizer';
import {createHash} from 'node:crypto';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import assert from 'node:assert/strict';

await Promise.all([MeshoptEncoder.ready,MeshoptDecoder.ready]);
const io=new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
const assets={};
await mkdir('public/studio/optimized',{recursive:true});
for(const [key,name]of [['world','sharkboom-world'],['mascot','shark-mascot']]){
  const original=await readFile(`public/studio/${name}.glb`);
  const document=await io.readBinary(original);
  await document.transform(dedup(),weld(),meshopt({encoder:MeshoptEncoder,level:'high',quantizePosition:14,quantizeNormal:10,quantizeWeight:12,cleanup:false}),prune({keepLeaves:true,keepAttributes:true}));
  const result=await io.writeBinary(document);
  const hash=createHash('sha256').update(result).digest('hex').slice(0,12);
  const path=`/studio/optimized/${name}.${hash}.glb`;
  await writeFile(`public${path}`,result);
  // Vinext reserves .gz URLs for implicit content negotiation. A .bin URL is
  // served directly on both its production server and Sites static hosting.
  const compressed=gzipSync(result,{level:9});await writeFile(`public${path}.bin`,compressed);
  // Decode the actual output, not only the pre-encoded document.
  const decoded=await io.readBinary(result),root=decoded.getRoot();
  assert.equal(root.listSkins()[0].listJoints().length,6,'Preserve six-bone shark rig');
  assert.deepEqual(root.listAnimations().map(x=>x.getName()).sort(),['Shark_Gentle_Blink','Shark_Organic_Swim']);
  assert.equal(root.listTextures().length,0,'No texture stand-ins for volumetric models');
  for(const node of key==='world'?['SharkRig','Vessel','Globe','Living_ocean']:['SharkRig'])assert(root.listNodes().some(x=>x.getName()===node),`Keep animation node ${node}`);
  assert(result.byteLength<original.byteLength*.6,'Production model should be substantially smaller');
  assets[key]={path:path+'.bin',fallback:path,originalBytes:original.byteLength,decodedBytes:result.byteLength,bytes:compressed.byteLength,reduction:Math.round((1-compressed.byteLength/original.byteLength)*1000)/10};
}
await writeFile('public/studio/loading-metrics.json',JSON.stringify(assets,null,2)+'\n');
await writeFile('app/motion-3d/model-assets.ts',`// Generated by assets/3d/optimize-world.mjs. Content hashes prevent stale model caches.\nexport const WORLD_MODEL=${JSON.stringify(assets.world.path)};\nexport const WORLD_FALLBACK=${JSON.stringify(assets.world.fallback)};\nexport const MASCOT_MODEL=${JSON.stringify(assets.mascot.path)};\nexport const MASCOT_FALLBACK=${JSON.stringify(assets.mascot.fallback)};\n`);
console.log(JSON.stringify(assets,null,2));
